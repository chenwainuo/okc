from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CUT = ROOT / "third_party" / "cutlass_dl" / "cutlass"
MX = ROOT / "proj_rsi" / "candidates" / "mx"
BUILD = ROOT / "logs" / "mx_build"
SWEEP_BUILD = ROOT / "logs" / "cutlass_sweep_build"
FLAGS = ["-O3", "-gencode=arch=compute_90a,code=sm_90a", "--expt-relaxed-constexpr", "-DNDEBUG", "-std=c++17"]
SHAPES = [("qkv_gate", 128), ("qkv_gate", 256), ("o", 128), ("o", 256), ("pooler", 128), ("pooler", 256),
          ("unpooler", 128), ("unpooler", 256)]


def parse_cfg(name):
    """ws_64x64_c1x2_s14_e1[_nosmem]  (kernel ws, tile M x N (K = 64), cluster, stages, escapes)"""
    m = re.match(r"(ws|co)_(\d+)x(\d+)_c(\d)x(\d)_s(\d+)(?:a(\d+))?_e(\d+)(_nosmem)?(_r|_o)?(?:_x(\d+))?(?:_q(\d))?$", name)
    if not m:
        raise SystemExit("bad cfg name %s" % name)
    return {"k": m.group(1), "tm": int(m.group(2)), "tn": int(m.group(3)), "cm": int(m.group(4)), "cn": int(m.group(5)),
            "st": int(m.group(6)), "as": int(m.group(7) or 0), "esc": int(m.group(8)), "epi": "nosmem" if m.group(9) else "tma", "red": m.group(10) == "_r", "one": m.group(10) == "_o", "skip": int(m.group(11) or 0), "sched": int(m.group(12)) if m.group(12) else 1}


