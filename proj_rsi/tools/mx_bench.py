def build_one(name, timeout=600):
    d = BUILD / name
    d.mkdir(parents=True, exist_ok=True)
    (d / "cfg.cu").write_text(gen_cu(name))
    cmd = ["nvcc", *FLAGS, "-DMX_SKIP=%d" % parse_cfg(name)["skip"], "-DMX_SCHED=%d" % parse_cfg(name)["sched"], "-Xptxas", "-v", "-shared", "-Xcompiler", "-fPIC", "-cudart", "shared", "-I", str(MX),
           "-I", str(CUT / "include"), "-I", str(CUT / "tools" / "util" / "include"), "-o", str(d / "cfg.so"), str(d / "cfg.cu")]
    t0 = time.time()
    p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=timeout)
    log = p.stdout
    (d / "build.log").write_text(log)
    regs = max([int(x) for x in re.findall(r"Used (\d+) registers", log)] or [0])
    sp = re.findall(r"(\d+) bytes spill stores, (\d+) bytes spill loads", log)
    spill = max([int(a) + int(b) for a, b in sp] or [0])
    meta = {"name": name, "ok": p.returncode == 0, "s": round(time.time() - t0, 1), "regs": regs, "spill": spill,
            "serialized": "C7510" in log or "serialized" in log}
    if p.returncode:
        meta["err"] = "\n".join([l for l in log.splitlines() if "error" in l][:6]) or log[-2000:]
    (d / "meta.json").write_text(json.dumps(meta, indent=1))
    return meta


def cmd_build(a):
    names = a.cfgs.split(",")
    with ThreadPoolExecutor(a.jobs) as ex:
        for m in ex.map(build_one, names):
            print("%-36s %s %6.1fs regs %d spill %d%s" % (m["name"], "ok  " if m["ok"] else "FAIL", m["s"], m["regs"], m["spill"],
                  " SERIALIZED" if m["serialized"] else ""), flush=True)
            if not m["ok"]:
                print(m["err"], flush=True)


def time_graph_read(fn, flush, sink, reps):
    """median us of a CUDA-graph replay after a read-only pass over a > L2 buffer (the bake's / judge's cold-L2 method)"""
    import torch
    s = torch.cuda.Stream()
    s.wait_stream(torch.cuda.current_stream())
    with torch.cuda.stream(s):
        fn()
        fn()
    torch.cuda.current_stream().wait_stream(s)
    torch.cuda.synchronize()
    g = torch.cuda.CUDAGraph()
    with torch.cuda.graph(g):
        fn()
    ts = []
    for _ in range(reps):
        torch.sum(flush, 0, out=sink)
        a, b = torch.cuda.Event(enable_timing=True), torch.cuda.Event(enable_timing=True)
        a.record()
        g.replay()
        b.record()
        torch.cuda.synchronize()
        ts.append(a.elapsed_time(b) * 1e3)
    ts.sort()
    return ts[len(ts) // 2]


def cmd_bench(a):
    import torch
    sys.path.insert(0, str(ROOT / "muse_bf16_proj"))
    sys.path.insert(0, str(ROOT / "proj_rsi" / "tools"))
    import reference
    import plane_pack
    dev = torch.device("cuda")
    weights = reference.generate_weights(a.seed)
    flush = torch.ones(256 << 20, dtype=torch.uint8, device=dev)
    sink = torch.empty((), dtype=torch.int64, device=dev)
    ws = torch.zeros(64 << 20, dtype=torch.uint8, device=dev)
    tiny = torch.zeros(32, device=dev)
    ovh = time_graph_read(lambda: tiny.add_(1.0), flush, sink, a.reps)
    print("REPLAY_OVERHEAD %.2f us (read flush)" % ovh, flush=True)
    libs = {}
    for name in a.cfgs.split(","):
        meta = json.loads((BUILD / name / "meta.json").read_text())
        if not meta["ok"]:
            continue
        lib = ctypes.CDLL(str(BUILD / name / "cfg.so"))
        lib.mx_run.argtypes = [ctypes.c_void_p] * 4 + [ctypes.c_int] + [ctypes.c_void_p] * 2 + [ctypes.c_int] * 4 + [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_void_p]
        lib.mx_run.restype = ctypes.c_int
        info = (ctypes.c_longlong * 8)()
        lib.mx_info.argtypes = [ctypes.c_void_p]
        lib.mx_info(info)
        print("CFG %s regs %d local %d smem %d stages %d threads %d (ptxas regs %d spill %d)" % (name, info[0], info[1], info[2], info[3], info[4],
              meta["regs"], meta["spill"]), flush=True)
        libs[name] = (lib, parse_cfg(name))
    refs = {}
    for rn in [r for r in a.ref.split(",") if r]:
        p = SWEEP_BUILD / rn / "cfg.so"
        if p.exists():
            lib = ctypes.CDLL(str(p))
            lib.cfg_run.argtypes = [ctypes.c_void_p] * 3 + [ctypes.c_int] * 3 + [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_void_p, ctypes.c_int]
            refs[rn] = lib
    splits = {kv.split("=")[0]: int(kv.split("=")[1]) for kv in a.splits.split(",") if kv}
    packs = {}
    shapes = [s for s in SHAPES if "%s:%d" % s in a.shapes.split(",")] if a.shapes else SHAPES
    for layer, m in shapes:
        n = reference.out_features(layer, m)
        w = weights[layer][:n].contiguous()
        if layer not in packs:
            packs[layer] = plane_pack.pack(weights[layer].contiguous())
            ok, wdec = plane_pack.verify(weights[layer].contiguous(), packs[layer])
            packs[layer]["wdec"] = wdec
            assert ok
        pk = packs[layer]
        K = w.shape[1]
        data = reference.generate_input(m, layer, a.seed + m, dist="normal")
        x = data["x"].contiguous()
        wt = w.t().contiguous()
        ref_dec = torch.mm(x, pk["wdec"].t().contiguous())
        line = ["%-9s m=%d" % (layer, m)]
        t_torch = time_graph_read(lambda: torch.mm(x, wt), flush, sink, a.reps)
        line.append("torch %.2f" % t_torch)
        for rn, lib in refs.items():
            out = torch.empty(m, n, dtype=torch.bfloat16, device=dev)
            best = None
            for var in (0, 1, 2):
                fn = lambda var=var: lib.cfg_run(w.data_ptr(), x.data_ptr(), out.data_ptr(), n, m, K, ws.data_ptr(), ws.numel(),
                                                 torch.cuda.current_stream().cuda_stream, var)
                if fn() != 0:
                    continue
                t = time_graph_read(fn, flush, sink, a.reps)
                best = t if best is None else min(best, t)
            line.append("%s %.2f" % (rn, best if best else float("nan")))
        for name, (lib, c) in libs.items():
            out = torch.full((m, n), float("nan"), dtype=torch.bfloat16, device=dev)
            S = splits.get("%s:%d" % (layer, m), splits.get(layer, 1)) if c["red"] else 1

            def fn():
                return lib.mx_run(pk["buf"].data_ptr(), pk["esc_off"].data_ptr(), pk["esc_rk"].data_ptr(), pk["esc_d"].data_ptr(), pk["base"],
                                  x.data_ptr(), out.data_ptr(), n, m, K, S, ws.data_ptr(), ws.numel(), torch.cuda.current_stream().cuda_stream)
            rc = fn()
            torch.cuda.synchronize()
            if rc != 0:
                line.append("%s rc=%d" % (name, rc))
                continue
            if c["esc"]:
                okc, msg = reference.check_implementation(data, out, weights)
                rel = ((out.float() - torch.mm(x, wt).float()).norm() / torch.mm(x, wt).float().norm()).item()
                vtxt = "check %s rel %.1e%s" % ("ok" if okc else "FAIL", rel, "" if okc else " (" + msg + ")")
            else:
                rel = ((out.float() - ref_dec.float()).norm() / ref_dec.float().norm()).item()
                vtxt = "relDec %.1e" % rel
            t = time_graph_read(fn, flush, sink, a.reps)
            if c["skip"] & 64:
                torch.cuda.synchronize()
                ws.view(torch.int64)[4096:4096 + 8 * 1024].zero_()
                flush.sum()
                fn()
                torch.cuda.synchronize()
                ts_ = ws.view(torch.int64)[4096:4096 + 8 * 1024].view(1024, 8).cpu()
                ts_ = ts_[ts_[:, 4] > 0].double()
                t0 = ts_[:, [0, 5]].min()
                rel = (ts_ - t0) / 1e3
                q = lambda c: (rel[:, c].median().item(), rel[:, c].max().item())
                print("DBG %s %s: n=%d [median/max us from first CTA start] aux0 %.2f/%.2f list %.2f/%.2f cons-start %.2f/%.2f "
                      "first-wgmma %.2f/%.2f loop-done %.2f/%.2f apply %.2f/%.2f->%.2f/%.2f epi-done %.2f/%.2f" % ((name, layer, len(ts_)) +
                      q(0) + q(1) + q(5) + q(6) + q(4) + q(2) + q(3) + q(7)), flush=True)
            line.append("%s%s %.2f [%s]" % (name, "/S%d" % S if c["red"] else "", t, vtxt))
        print("  ".join(line), flush=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["build", "bench", "gen"])
    ap.add_argument("--cfgs", default="ws_64x64_c1x2_s14_e0")
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--shapes", default="")
    ap.add_argument("--ref", default="")
    ap.add_argument("--reps", type=int, default=30)
    ap.add_argument("--splits", default="pooler=2,qkv_gate=4,unpooler=1,o=1")
    ap.add_argument("--seed", type=int, default=1234)
    a = ap.parse_args()
    if a.cmd == "build":
        cmd_build(a)
    elif a.cmd == "gen":
        for n in a.cfgs.split(","):
            print(gen_cu(n))
    else:
        cmd_bench(a)


if __name__ == "__main__":
    main()
