"""Build / validate / time the mx two-plane CUTLASS GEMM (proj_rsi/candidates/mx/mx_mainloop.hpp) on the H100 box.

Each config is one .cu -> plain .so (ctypes), like cutlass_sweep.py. Swap-AB: A = packed W planes (M = W rows),
B = x [tok][K] (K-major), D = out [tok][n] (column-major M x N).

  python proj_rsi/tools/mx_bench.py build [--cfgs a,b] [--jobs 8]            (no GPU lock needed)
  /root/gpu_lock.sh /root/okc_run.sh python proj_rsi/tools/mx_bench.py bench [--cfgs ...] [--shapes pooler:128,...] [--ref ws_64x64x64_c1x2_sA_tma]
"""

from __future__ import annotations

import argparse
import ctypes
