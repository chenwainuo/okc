"""CPU-only exact-metric/catalog, frozen-source and raw-parser rejection gates."""
from __future__ import annotations
import ast
import csv
import gzip
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import re
import subprocess

import parse_report as P

HERE = Path(__file__).resolve().parent


def main():
    sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
    for path in HERE.glob("*.py"):
        ast.parse(path.read_text())
    subprocess.run(["bash", "-n", str(HERE / "run.sh")], check=True)
    full = gzip.decompress((HERE / "ncu-gh100-all.txt.gz").read_bytes()).decode()
    launch = (HERE / "ncu-gh100-launch.txt").read_text()
    assert "Chip gh100" in full and "2025.1.1.0" in (HERE / "ncu-version.txt").read_text()
    for metric in P.METRICS:
        catalog = launch if metric.startswith("launch__") else full
        assert re.search(r"^" + re.escape(metric) + r"\s", catalog, re.M), "unsupported/unproven metric " + metric
    assert (HERE / "metrics.txt").read_text().strip().split(",") == P.METRICS
    section = (HERE / "MemoryWorkloadAnalysis.section").read_text()
    assert 'Name: "lrc__ilc_input_sectors.sum"' in section and "MinArch: CC_90" in section
    assert "decompress" not in (HERE / "ncu-gh100-base.txt").read_text().lower()
    native = HERE.parent / "hw_native"
    assert sha(native / "lab.py") == "0a4db150debff8dfd09d13d33fe97896a27ba39a272e1b7f00b71f7a803c8047"
    for directory in [native, HERE.parent / "hw_compression_owner"]:
        manifest = json.loads((directory / "manifest.json").read_text())
        assert all(sha(directory / n) == h for n, h in manifest["sha256"].items())
    d = ast.parse((HERE / "driver.py").read_text())
    calls = [n.func.attr for n in ast.walk(d) if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute)]
    assert not set(calls) & {"prepare", "_tune", "_ltsearch", "_time_us", "measure", "profile"}
    assert calls.count("lt_add") == 1 and "range_push" in calls
    # Base-unit parser fixture, not measured evidence. Exercise zero-ILC denominators honestly.
    header = ["ID", "Kernel Name", "thread Domain:Push/Pop_Range:PL_Type:PL_Value:CLR_Type:Color:Msg_Type:Msg"] + P.METRICS
    units = {name: "" for name in header}
    for direction in ["read", "write"]:
        units[f"dram__bytes_{direction}.sum"] = "byte"
        units[f"dram__sectors_{direction}.sum"] = "sector"
    rows = []
    for index, label in enumerate(["compression_generic", "compression_none"]):
        row = {name: "0" for name in header}
        row.update({"ID": str(index), "Kernel Name": P.KERNEL,
                    header[2]: '34 "<default domain>:' + label + ':none:none:none:none:none:none"'})
        for direction in ["read", "write"]:
            sectors = (1048576 if index == 0 else 2097152) if direction == "read" else 65536
            row[f"dram__sectors_{direction}.sum"] = str(sectors)
            row[f"dram__bytes_{direction}.sum"] = str(sectors * 32)
        for name, value in zip(P.LAUNCH, [1, 128, 1, 384, 1, 1, 168, 213268]):
            row[name] = str(value)
        for name in P.ILC[3:]:
            row[name] = "n/a"
        rows.append(row)
    def rendered(unit, values):
        out = io.StringIO(); writer = csv.DictWriter(out, fieldnames=header)
        writer.writeheader(); writer.writerow(unit); writer.writerows(values)
        # CSV generated by DictWriter's default minimal quoting needs a canonical NCU header.
        return out.getvalue().replace("ID,Kernel Name,", '"ID","Kernel Name",', 1)
    fixture = rendered(units, rows)
    parsed = P.parse_text(fixture)
    assert parsed["observed_DRAM_read_reduction_pct"] == 50
    assert parsed["runtime_unavailable_ILC_metrics"] == P.ILC[3:]
    rejects = 0
    for broken in [rendered(dict(units, **{"dram__bytes_read.sum": "Mbyte"}), rows),
                   rendered(units, [dict(rows[0], **{"Kernel Name": "wrong_shader"}), rows[1]]),
                   rendered(units, [rows[0], dict(rows[1], **{header[2]: rows[0][header[2]]})]),
                   rendered(units, [rows[0]])]:
        try:
            P.parse_text(broken)
        except (AssertionError, KeyError):
            rejects += 1
        else:
            raise AssertionError("raw report corruption accepted")
    result = {"state": "CPU_METADATA_SOURCE_PARSER_PASS_GPU_UNRUN", "CUDA_API_calls": 0,
              "supported_metric_names": P.METRICS, "raw_parser_negative_controls": rejects,
              "zero_ILC_denominator_handling": "UNKNOWN_NOT_ZERO_COMPRESSION",
              "fixed_config": [66, 18, 1, 0, 0, 4, 35, 0, 2], "prepare_or_autotune_calls": 0}
    (HERE / "preflight.json").write_text(json.dumps(result, indent=2) + "\n")
    files = [p.name for p in HERE.iterdir() if p.is_file() and p.name != "manifest.json"]
    manifest = {"state": "COUNTER_DIAGNOSTIC_FROZEN_FOR_REVIEW_GPU_UNRUN",
                "sha256": {n: sha(HERE / n) for n in sorted(files)}}
    (HERE / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(result, indent=2)); print("MANIFEST", sha(HERE / "manifest.json"))


if __name__ == "__main__": main()
